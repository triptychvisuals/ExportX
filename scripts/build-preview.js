'use strict';
/**
 * Bundle the panel into one HTML file that runs against the fake Resolve in
 * ui/mock-api.js, so anyone can open it in a browser and click around.
 *
 *   node scripts/build-preview.js                 -> docs/preview.html (standalone, open locally)
 *   node scripts/build-preview.js --fragment out  -> body fragment without doctype/html/head (for hosts that wrap it)
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');

const fragment = process.argv.includes('--fragment');
const outArg = process.argv.find((a, i) => i > 1 && !a.startsWith('--'));
const out = outArg ? path.resolve(outArg) : path.join(root, 'docs', 'preview.html');

const html = read('ui/index.html');
let css = read('ui/styles.css');
const renderer = read('ui/renderer.js');
const mock = read('ui/mock-api.js');
const profiles = JSON.parse(read('profiles/default.json')).profiles;
const version = JSON.parse(read('package.json')).version;
const videoPath = path.join(root, 'ui', 'mock-preview.webm');
const videoUri = fs.existsSync(videoPath) ? `data:video/webm;base64,${fs.readFileSync(videoPath).toString('base64')}` : null;

// Fonts: the plugin bundles woff2 files; the preview loads the same faces from Google Fonts.
css = css.replace(/@font-face\s*\{[^}]*\}\s*/g, '');
const fontsLink =
  '<link rel="preconnect" href="https://fonts.googleapis.com">\n' +
  '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Wix+Madefor+Display:wght@600;700;800&family=Wix+Madefor+Text:wght@400;500;600;700&display=swap">';

const body = html.slice(html.indexOf('<body>') + '<body>'.length, html.lastIndexOf('</body>')).replace(/<script src="renderer.js"><\/script>\s*/, '');

const note =
  '<div class="preview-note" role="note">Preview with a fake Resolve and a test-pattern video standing in for your timeline. Hold the pad to mark a cut, tap it for a still, press Export, and try the Settings tab. Nothing is rendered or saved.</div>\n';
const noteCss =
  '.preview-note{background:var(--x-surface);color:var(--x-text-2);border-bottom:1px solid var(--x-line);font-size:12px;padding:8px max(16px,env(safe-area-inset-right,0px)) 8px max(16px,env(safe-area-inset-left,0px));text-align:center}';

const scripts =
  `<script>window.__EXPORTX_PROFILES__ = ${JSON.stringify(profiles)};${videoUri ? ` window.__EXPORTX_PREVIEW_VIDEO__ = ${JSON.stringify(videoUri)};` : ''}</script>\n` +
  `<script>\n${mock}\n</script>\n` +
  `<script>\n${renderer}\n</script>`;

const title = '<title>ExportX</title>';
const inner = `${title}\n${fontsLink}\n<style>\n${css}\n${noteCss}\n</style>\n${note}${body}\n${scripts}\n`;

const doc = fragment
  ? inner
  : `<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1">\n<!-- ExportX ${version} preview, generated by scripts/build-preview.js -->\n</head>\n<body>\n${inner}</body>\n</html>\n`;

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, doc);
console.log(`Wrote ${out} (${(doc.length / 1024).toFixed(0)} KB${fragment ? ', fragment' : ''})`);
